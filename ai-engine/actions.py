"""Predefined Allowlisted Workflow Actions for FlowForge AI.

Only actions defined and approved in this registry are permitted in generated workflows.
Arbitrary actions generated by the LLM or external callers must be strictly rejected.
"""

from typing import Dict, Any, List, Optional

# Approved workflow actions dictionary
# Each action contains human-readable description, allowed parameters, and required parameters.
ALLOWLISTED_ACTIONS: Dict[str, Dict[str, Any]] = {
    "create_registration_page": {
        "description": "Create an event, class, or workshop registration landing page.",
        "allowed_parameters": ["title", "capacity", "description", "event_date"],
        "required_parameters": [],
    },
    "create_booking_page": {
        "description": "Create an appointment or service scheduling booking page.",
        "allowed_parameters": ["service_name", "duration_minutes", "description"],
        "required_parameters": [],
    },
    "create_order_checkout": {
        "description": "Create an online checkout page for selling physical or digital products.",
        "allowed_parameters": ["product_name", "price", "currency", "quantity"],
        "required_parameters": [],
    },
    "collect_customer_details": {
        "description": "Collect required customer information (e.g. name, email, phone, notes).",
        "allowed_parameters": ["fields", "required_fields"],
        "required_parameters": [],
    },
    "schedule_appointment_slot": {
        "description": "Reserve a designated appointment time slot in the business schedule.",
        "allowed_parameters": ["calendar_id", "slot_duration"],
        "required_parameters": [],
    },
    "create_paypal_order": {
        "description": "Initialize a PayPal payment order for transactions.",
        "allowed_parameters": ["amount", "currency", "intent", "description"],
        "required_parameters": ["amount", "currency"],
    },
    "verify_payment": {
        "description": "Verify PayPal payment capture, authorized status, and settlement.",
        "allowed_parameters": ["provider", "required_status"],
        "required_parameters": [],
    },
    "send_confirmation_email": {
        "description": "Send an automated confirmation email with receipt or booking details.",
        "allowed_parameters": ["template", "subject", "recipient_field"],
        "required_parameters": [],
    },
    "send_notification": {
        "description": "Send an SMS, push notification, or internal alert.",
        "allowed_parameters": ["channel", "message_template"],
        "required_parameters": [],
    },
}


def is_action_allowed(action_name: str) -> bool:
    """Check if the given action name is in the approved allowlist."""
    return action_name in ALLOWLISTED_ACTIONS


def get_action_metadata(action_name: str) -> Optional[Dict[str, Any]]:
    """Return metadata for an allowlisted action, or None if disallowed."""
    return ALLOWLISTED_ACTIONS.get(action_name)


def get_allowed_actions_list() -> List[str]:
    """Return list of all approved action names."""
    return sorted(list(ALLOWLISTED_ACTIONS.keys()))


def format_actions_for_prompt() -> str:
    """Format the approved actions list into a clear markdown string for LLM prompts."""
    lines = []
    for action, meta in sorted(ALLOWLISTED_ACTIONS.items()):
        params_str = ", ".join(meta["allowed_parameters"]) if meta["allowed_parameters"] else "none"
        req_str = ", ".join(meta["required_parameters"]) if meta["required_parameters"] else "none"
        lines.append(
            f"- `{action}`: {meta['description']} (Allowed params: [{params_str}], Required: [{req_str}])"
        )
    return "\n".join(lines)

